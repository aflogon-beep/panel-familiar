var MONS=['ene','feb','mar','abr','may','jun','jul','ago','sep','oct','nov','dic'];
var pad=function(n){return String(n).padStart(2,'0')};
var mk=function(y,m,d){return new Date(y,m,d,12)};
var day0=function(d){d=d||new Date();return mk(d.getFullYear(),d.getMonth(),d.getDate())};
var today=function(){return day0()};
var iso=function(d){return d.getFullYear()+'-'+pad(d.getMonth()+1)+'-'+pad(d.getDate())};
var fromIso=function(s){var p=s.split('-').map(Number);return mk(p[0],p[1]-1,p[2])};
var add=function(d,n){return mk(d.getFullYear(),d.getMonth(),d.getDate()+n)};
var dow=function(d){return (d.getDay()+6)%7};
var monOf=function(d){return add(d,-dow(d))};
var dd=function(a,b){return Math.round((b-a)/MS)};
var mins=function(t){var p=t.split(':');return +p[0]*60+ +p[1]};
var hm=function(m){return pad(Math.floor(m/60))+':'+pad(m%60)};
var ESC={'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'};
var esc=function(s){return String(s).replace(/[&<>"']/g,function(c){return ESC[c]})};
var norm=function(s){return String(s).toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g,'').trim()};
var cap=function(s){return s.charAt(0).toUpperCase()+s.slice(1)};
var human=function(m){return m<60?m+' min':Math.floor(m/60)+' h'+(m%60?' '+(m%60)+' min':'')};
var dl=function(d){return DOWS[dow(d)]+' '+d.getDate()+' '+MONS[d.getMonth()]};
var ic=function(n,c){return '<svg class="ic'+(c?' '+c:'')+'" aria-hidden="true"><use href="#i-'+n+'"/></svg>'};
var nid=function(p){return p+Date.now().toString(36)+Math.random().toString(36).slice(2,6)};
